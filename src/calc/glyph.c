void glyph_draw(int x, int y, const glyph_t *g, int left, int top, int right, int bottom) {
	int row, column;

	for (row = 0; row < 8; row++) {
		for (column = 0; column < 8; column++) {
			int px = x + column, py = y + row;

			if ((g->rows[row] & (0x80 >> column)) && px >= left && px < right && py >= top && py < bottom)
				gfx_SetPixel(px, py);
		}
	}
}

